package db.model;

/**
 Типы данных, которые поддерживает наша СУБД.
 Используются в схеме таблицы для проверки типов при вставке и обновлении.
 */
public enum DataType {
    INT,        // целое число
    DOUBLE,     // число с плавающей точкой
    STRING,     // строка
    DATE,       // дата
    BOOLEAN     // логическое значение
}